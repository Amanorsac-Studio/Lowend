#!/usr/bin/env node
// make-tester-test-vectors.js — writes tests/TesterVectors.h.
//
// The unit tests for TesterGate.h need real signed tokens. They are made here with
// a THROWAWAY key pair whose private half is discarded the moment the header is
// written, so the tests never need, and never see, the real signing key. Node's
// own crypto signs them, which is what makes this a check of the C++ against an
// independent implementation of the same standard rather than against itself.
'use strict';
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const b64u = b => Buffer.from(b).toString('base64url');
const pair = () => crypto.generateKeyPairSync('rsa', { modulusLength: 2048, publicExponent: 65537 });
const nHex = pub => Buffer.from(pub.export({ format: 'jwk' }).n, 'base64url').toString('hex');
const token = (priv, obj) => { const body = JSON.stringify(obj); return b64u(body) + '.' + b64u(crypto.sign('sha256', Buffer.from(body), priv)); };
const cstr = s => '"' + s.match(/.{1,96}/g).join('"\n    "') + '"';

const A = pair(), B = pair();
const YEAR2100 = 4102444800000, YEAR2001 = 978307200000, ISSUED = Date.UTC(2026, 8, 21), DAY = 86400000;
const P = 'lowend-tester';

const v = {
  Modulus:      nHex(A.publicKey),
  OtherModulus: nHex(B.publicKey),
  Good:         token(A.privateKey, { a: P, i: ISSUED, e: ISSUED + 30 * DAY, n: '0a0b0c0d' }),
  Long:         token(A.privateKey, { a: P, i: ISSUED, e: YEAR2100, n: '01020304' }),
  Expired:      token(A.privateKey, { a: P, i: YEAR2001 - 30 * DAY, e: YEAR2001, n: '11111111' }),
  FromFuture:   token(A.privateKey, { a: P, i: YEAR2100 - 30 * DAY, e: YEAR2100, n: '22222222' }),
  WrongProduct: token(A.privateKey, { a: 'something-else', i: ISSUED, e: YEAR2100, n: '33333333' }),
  NoDates:      token(A.privateKey, { a: P, n: '44444444' }),
  BackwardsDates: token(A.privateKey, { a: P, i: YEAR2100, e: ISSUED, n: '55555555' }),
  SignedByOther: token(B.privateKey, { a: P, i: ISSUED, e: YEAR2100, n: '66666666' }),
};

let out = `// TesterVectors.h — GENERATED by scripts/make-tester-test-vectors.js. Do not edit.
// Tokens signed by a throwaway key pair (the private half was discarded); see that script.
#pragma once
namespace testervectors {
constexpr long long kIssuedMs = ${ISSUED}LL;   // 2026-09-21T00:00:00Z
constexpr long long kGoodExpiresMs = ${ISSUED + 30 * DAY}LL;
constexpr long long kExpiredExpiresMs = ${YEAR2001}LL;
`;
for (const [k, s] of Object.entries(v)) out += `inline constexpr const char* k${k} =\n    ${cstr(s)};\n`;
out += '}\n';
fs.writeFileSync(path.join(__dirname, '..', 'tests', 'TesterVectors.h'), out);
console.log('wrote tests/TesterVectors.h with', Object.keys(v).length, 'vectors');
